import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from xgboost import XGBClassifier
from sklearn.metrics import confusion_matrix
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score
import shap
import matplotlib.pyplot as plt

"""**DATASET UPLOAD**"""

dataset = pd.read_csv("/content/Customer-Churn-Records.csv")

"""**DATA CLEANING**"""

print(dataset.info()) #Dimentionality
print(dataset.duplicated().sum()) #Duplicates
print(dataset.isnull().sum()) #Null values

dataset = dataset.drop(columns=["RowNumber", "CustomerId", "Surname"])

print(dataset["CreditScore"].unique()) #Check inconsistent values in each column
print(dataset["Geography"].unique())
print(dataset["Gender"].unique())
print(dataset["Age"].unique())
print(dataset["Tenure"].unique())
print(dataset["Balance"].unique())
print(dataset["NumOfProducts"].unique())
print(dataset["HasCrCard"].unique())
print(dataset["IsActiveMember"].unique())
print(dataset["EstimatedSalary"].unique())
print(dataset["Exited"].unique())
print(dataset["Complain"].unique())
print(dataset["Satisfaction Score"].unique())
print(dataset["Card Type"].unique())
print(dataset["Point Earned"].unique())

"""**EXPLORATORY DATA ANALYSIS**

*Target Variable: Exited*
"""

print(dataset["Exited"].value_counts(normalize=True) * 100)
dataset["Exited"].value_counts().plot(kind="bar")

plt.title("Customer Churn")
plt.xlabel("Exited")
plt.ylabel("Number of Customers")
plt.show()

"""*Numerical predictors*"""

print(dataset.describe())

numerical_columns = [
    "CreditScore",
    "Age",
    "Tenure",
    "Balance",
    "NumOfProducts",
    "EstimatedSalary",
    "Point Earned",
    "Satisfaction Score"
]

print(dataset.groupby("Exited")[numerical_columns].mean())

"""*Catgeorical predictors*"""

categorical_columns = [
    "Geography",
    "Gender",
    "HasCrCard",
    "IsActiveMember",
    "Complain",
    "Card Type"
]
for column in categorical_columns:
    print("\n", column)
    print(dataset.groupby(column)["Exited"].mean() * 100)

"""*Correlation*"""

correlation = dataset.corr(numeric_only=True)

plt.figure(figsize=(10, 8))

sns.heatmap(
    correlation,
    annot=True,
    cmap="coolwarm",
    fmt=".2f"
)

plt.title("Correlation Matrix")
plt.show()

"""**FEATURE ENGENEERING**"""

dataset["HasBalance"] = (dataset["Balance"] > 0).astype(int) #Create new variable

dataset = pd.get_dummies( #One hot encoding
    dataset,
    columns=["Geography", "Gender", "Card Type"],
    drop_first=True
)

X = dataset.drop("Exited", axis=1)#Separate predictos and target variable
y = dataset["Exited"]

"""**SPLIT TRAIN/TEST**"""

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

"""**MODEL TRAINING**"""

scale_pos_weight = (y_train == 0).sum() / (y_train == 1).sum()
model = XGBClassifier(
    n_estimators=200, # num of trees
    learning_rate=0.05, # how strong the contribution of each tree is
    max_depth=4, # for each tree
    scale_pos_weight=scale_pos_weight,
    random_state=42, # to be able to repeat
    eval_metric="logloss"
)

model.fit(X_train, y_train)

y_pred = model.predict(X_test) # binary of leave or stay
y_pred_proba = model.predict_proba(X_test)[:, 1] # prob of leave

"""**MODEL EVALUATION**"""

cm = confusion_matrix(y_test, y_pred)

print(cm)

importance = pd.Series(
    model.feature_importances_,
    index=X_train.columns
).sort_values(ascending=False)

print(importance)

X_no_complain = X.drop("Complain", axis=1)

X_train_nc, X_test_nc, y_train_nc, y_test_nc = train_test_split(
    X_no_complain,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)
scale_pos_weight = (y_train_nc == 0).sum() / (y_train_nc == 1).sum()
model_nc = XGBClassifier(
    n_estimators=200, # num of trees
    learning_rate=0.05, # how strong the contribution of each tree is
    max_depth=4, # for each tree
    scale_pos_weight=scale_pos_weight,
    random_state=42, # to be able to repeat
    eval_metric="logloss"
)

model_nc.fit(X_train_nc, y_train_nc)

y_pred_nc = model_nc.predict(X_test_nc) # binary of leave or stay
y_pred_proba_nc = model_nc.predict_proba(X_test_nc)[:, 1] # prob of leave

cm = confusion_matrix(y_test_nc, y_pred_nc)

print(cm)

print("Accuracy:", accuracy_score(y_test, y_pred))
print("Precision:", precision_score(y_test, y_pred))
print("Recall:", recall_score(y_test, y_pred))
print("F1:", f1_score(y_test, y_pred))
print("ROC-AUC:", roc_auc_score(y_test, y_pred_proba))

"""**INTERPRETATION AND RECOMMENDATIONS**"""

importance = pd.Series(
    model_nc.feature_importances_,
    index=X_train_nc.columns
).sort_values(ascending=False)

print(importance)

importance.sort_values().plot(kind="barh", figsize=(10, 6))

plt.xlabel("Feature Importance")
plt.ylabel("Feature")
plt.title("XGBoost Feature Importance")
plt.show()

print(
    dataset.groupby("NumOfProducts")["Exited"]
    .mean()
    .mul(100)
)

print(
    dataset.groupby("IsActiveMember")["Exited"]
    .mean()
    .mul(100)
)

age_bins = [18, 25, 35, 45, 55, 65, 100]
age_labels = ["18-25", "26-35", "36-45", "46-55", "56-65", "66+"]

dataset["AgeGroup"] = pd.cut(
    dataset["Age"],
    bins=age_bins,
    labels=age_labels,
    include_lowest=True
)

print(
    dataset.groupby("AgeGroup", observed=True)["Exited"]
    .mean()
    .mul(100)
)

"""EXPLAINABLE AI"""

explainer = shap.TreeExplainer(model)
shap_values = explainer.shap_values(X_test_nc)

shap.summary_plot(shap_values, X_test_nc)